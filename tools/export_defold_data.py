"""Export the shared game content into the Defold build as a Lua module.

The Godot build reads data/content.json; Defold has no JSON reader of its own, so
the same file is turned into a Lua table. Run with --check in CI to make sure the
export never drifts from the source of truth.
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / "data" / "content.json"
TARGET = ROOT / "defold" / "main" / "data" / "content.lua"
KEYS = ["professions", "skills", "baggage", "health", "facts", "qualities", "ages"]


def lua_string(value: str) -> str:
    return '"' + value.replace("\\", "\\\\").replace('"', '\\"') + '"'


def lua_value(value) -> str:
    """Strings stay strings, health entries keep their label and cost."""
    if isinstance(value, str):
        return lua_string(value)
    if isinstance(value, dict):
        parts = [f'{name} = {lua_value(item)}' for name, item in value.items()]
        return "{ " + ", ".join(parts) + " }"
    if isinstance(value, int):
        return str(value)
    return lua_string(str(value))


def render(content: dict) -> str:
    lines = [
        "-- Generated by tools/export_defold_data.py from data/content.json.",
        "-- Do not edit: change the JSON and re-run the exporter.",
        "return {",
    ]
    for key in KEYS:
        values = content[key]
        lines.append(f"\t{key} = {{")
        for value in values:
            lines.append(f"\t\t{lua_value(value)},")
        lines.append("\t},")
    lines.append("}")
    return "\n".join(lines) + "\n"


def main(argv: list[str]) -> int:
    content = json.loads(SOURCE.read_text(encoding="utf-8"))
    text = render(content)
    if "--check" in argv:
        current = TARGET.read_text(encoding="utf-8") if TARGET.exists() else ""
        if current != text:
            print("defold/main/data/content.lua is stale; run tools/export_defold_data.py")
            return 1
        print(f"Defold content is current: {len(content['professions'])} professions")
        return 0
    TARGET.parent.mkdir(parents=True, exist_ok=True)
    TARGET.write_text(text, encoding="utf-8")
    print(f"wrote {TARGET.relative_to(ROOT)}: {len(content['professions'])} professions")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
